"""Generate the TO-BE BPMN models of process 1 (Movia travel guarantee).

  uv run --project service python tools/build_to_be_bpmn.py

Writes to models/to-be/:

  assess-disruption.bpmn        executable, one instance per delay
  decide-claim.bpmn             executable, one instance per claim (pays out too)
  handle-appeal.bpmn            executable, one instance per appeal
  passenger-journey.bpmn        the passenger's side; not executable
  collaboration-overview.bpmn   the four as collapsed pools, with the messages between them

and, next to each executable model, a <name>.processdoctor.bpmn copy for processdoctor.compute.dtu.dk.
processdoctor reads only the first <bpmn:process> of a file and only plain <bpmn:task> elements, so the
copy has the same ids, names and layout with every typed task (service, business rule, user) written as
a plain task. Every model keeps to processdoctor's other rules: one start event, every task one flow in
and one out, every gateway split closed by a join of the same type.

Activity names come from service/rejsegaranti/activities.py. Don't hand-edit the .bpmn files.
"""
from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "service"))
from bpmn_layout import Process, document  # noqa: E402
from rejsegaranti import activities as A  # noqa: E402

OUT = os.path.join(HERE, "..", "models", "to-be")
HTTL = ' camunda:historyTimeToLive="180"'
AUTHOR = "Author: Liam Palmqvist. TO-BE of process 1, the Movia travel guarantee. Generated by tools/build_to_be_bpmn.py."

# grid: column and row centres
X0, DX, Y0, DY = 230, 150, 0, 130


def col(c: float) -> float:
    return X0 + c * DX


def service(name: str) -> str:
    return f' camunda:type="external" camunda:topic="{A.TOPICS[name]}"'


def rule(decision: str, **outputs: str) -> tuple:
    """A business rule task's attributes and body. Each output of the decision becomes a plain process variable
    (an output mapping), so gateways and workers read e.g. `covered` instead of a serialized result map."""
    params = "".join(f'<camunda:outputParameter name="{var}">${{decisionResult.getSingleResult().{out}}}'
                     f"</camunda:outputParameter>" for var, out in outputs.items())
    return (f' camunda:decisionRef="{decision}"',
            f"<bpmn:extensionElements><camunda:inputOutput>{params}</camunda:inputOutput></bpmn:extensionElements>")


EXCL = rule("ToBe_Exclusion", exclusion="exclusion")
VALID = rule("ToBe_ClaimValid", claimValid="claimValid", claimReason="claimReason")
GUAR = rule("ToBe_TravelGuarantee", covered="covered", guaranteeReason="reason")
REFUND = rule("ToBe_Refund", refundDkk="refundDkk")


def message_start(msg: str) -> str:
    return f'<bpmn:messageEventDefinition id="Def_{msg}" messageRef="Message_{msg}" />'


class Grid(Process):
    """A pool whose elements are placed on a grid of columns and rows (row 0 is the main path)."""

    def __init__(self, id, name, executable, top, rows, lanes=None):
        self.top, self.rows = top, rows  # rows: (first row, last row) used inside the pool
        self.row_y = lambda r: top + 70 + (r - rows[0]) * DY
        super().__init__(id, name, executable, pool=None, lanes=lanes,
                         extra_attrs=HTTL if executable else "")

    def put(self, id, type, name, c, r=0, attrs="", body="", lane=None, label="below"):
        return self.add(id, type, name, col(c), self.row_y(r), attrs, body, lane, label)

    def close(self, last_col: float):
        h = (self.rows[1] - self.rows[0]) * DY + 140
        self.pool = (100, self.top, col(last_col) + 90 - 100, h)
        return self

    def detour(self, src, tgt, r, name="", cond=None):
        """A branch that leaves `src` on another row and comes back into `tgt` (an empty branch)."""
        a, b = self.nodes[src], self.nodes[tgt]
        y = self.row_y(r)
        up = y < a.y
        wp = [a.top if up else a.bottom, (a.x, y), (b.x, y), b.top if up else b.bottom]
        return self.flow(src, tgt, name, cond, wp=wp)


def lane_rows(p: Grid, lanes):
    """[(lane id, name, first row, last row)] -> laneSet tuples (id, name, y, h)."""
    out = []
    for lid, name, r0, r1 in lanes:
        y = p.row_y(r0) - 70 if r0 == p.rows[0] else p.row_y(r0) - DY / 2
        y2 = p.row_y(r1) + 70 if r1 == p.rows[1] else p.row_y(r1) + DY / 2
        out.append((lid, name, y, y2 - y))
    return out


# ---- Assess disruption -----------------------------------------------------------------------------

def assess_disruption() -> Grid:
    p = Grid(A.ASSESS_KEY, "Movia: assess disruption (once per delay)", True, top=60, rows=(0, 1))
    p.put("Start_Delay", "startEvent", A.DELAY_REPORTED, 0, body=message_start(A.DELAY_MESSAGE))
    p.put("Task_Collect", "serviceTask", A.COLLECT_DISRUPTION, 1, attrs=service(A.COLLECT_DISRUPTION))
    p.put("Task_Exclusion", "businessRuleTask", A.DECIDE_EXCLUSION, 2,
          attrs=EXCL[0], body=EXCL[1])
    p.put("Gateway_CanApply", "exclusiveGateway", "Guarantee can apply?", 3, label="above")
    p.put("Task_Notify", "serviceTask", A.NOTIFY_PASSENGERS, 4, attrs=service(A.NOTIFY_PASSENGERS))
    p.put("Gateway_CanApplyJoin", "exclusiveGateway", "", 5)
    p.put("Task_Publish", "serviceTask", A.PUBLISH_ASSESSMENT, 6, attrs=service(A.PUBLISH_ASSESSMENT))
    p.put("End_Assessed", "endEvent", A.DISRUPTION_ASSESSED, 7)
    p.flow("Start_Delay", "Task_Collect")
    p.flow("Task_Collect", "Task_Exclusion")
    p.flow("Task_Exclusion", "Gateway_CanApply")
    p.flow("Gateway_CanApply", "Task_Notify", "yes", '${exclusion == "none"}')
    p.detour("Gateway_CanApply", "Gateway_CanApplyJoin", 1, "no (excluded)", '${exclusion != "none"}')
    p.flow("Task_Notify", "Gateway_CanApplyJoin")
    p.flow("Gateway_CanApplyJoin", "Task_Publish")
    p.flow("Task_Publish", "End_Assessed")
    return p.close(7)


# ---- Decide claim and pay out ----------------------------------------------------------------------

def decide_claim() -> Grid:
    p = Grid(A.CLAIM_KEY, "Movia: decide claim and pay out (once per claim)", True, top=60, rows=(-1, 1))
    p.put("Start_Claim", "startEvent", A.CLAIM_SUBMITTED, 0, body=message_start(A.CLAIM_MESSAGE))
    p.put("Task_Validity", "businessRuleTask", A.CHECK_VALIDITY, 1, attrs=VALID[0], body=VALID[1])
    p.put("Gateway_Valid", "exclusiveGateway", "Claim valid?", 2)
    p.put("Task_Match", "serviceTask", A.MATCH_CLAIM, 3, attrs=service(A.MATCH_CLAIM))
    p.put("Task_Guarantee", "businessRuleTask", A.DECIDE_GUARANTEE, 4,
          attrs=GUAR[0], body=GUAR[1])
    p.put("Gateway_Covered", "exclusiveGateway", "Covered?", 5, label="above")
    p.put("Task_Refund", "businessRuleTask", A.CALC_REFUND, 6, attrs=REFUND[0], body=REFUND[1])
    p.put("Task_PayOut", "serviceTask", A.PAY_OUT, 7, attrs=service(A.PAY_OUT))
    p.put("Task_RejectNotCovered", "serviceTask", A.REJECT_NOT_COVERED, 6.5, 1,
          attrs=service(A.REJECT_NOT_COVERED))
    p.put("Gateway_CoveredJoin", "exclusiveGateway", "", 8)
    p.put("Task_RejectInvalid", "serviceTask", A.REJECT_INVALID, 5.5, -1, attrs=service(A.REJECT_INVALID))
    p.put("Gateway_ValidJoin", "exclusiveGateway", "", 9)
    p.put("Task_Send", "serviceTask", A.SEND_DECISION, 10, attrs=service(A.SEND_DECISION))
    p.put("End_Decided", "endEvent", A.CLAIM_DECIDED, 11)
    p.flow("Start_Claim", "Task_Validity")
    p.flow("Task_Validity", "Gateway_Valid")
    p.flow("Gateway_Valid", "Task_Match", "yes", "${claimValid}")
    p.flow("Gateway_Valid", "Task_RejectInvalid", "no", "${!claimValid}")
    p.flow("Task_Match", "Task_Guarantee")
    p.flow("Task_Guarantee", "Gateway_Covered")
    p.flow("Gateway_Covered", "Task_Refund", "yes", "${covered}")
    p.flow("Gateway_Covered", "Task_RejectNotCovered", "no", "${!covered}")
    p.flow("Task_Refund", "Task_PayOut")
    p.flow("Task_PayOut", "Gateway_CoveredJoin")
    p.flow("Task_RejectNotCovered", "Gateway_CoveredJoin")
    p.flow("Gateway_CoveredJoin", "Gateway_ValidJoin")
    p.flow("Task_RejectInvalid", "Gateway_ValidJoin")
    p.flow("Gateway_ValidJoin", "Task_Send")
    p.flow("Task_Send", "End_Decided")
    return p.close(11)


# ---- Handle appeal ---------------------------------------------------------------------------------

REVIEW_FORM = ('<bpmn:extensionElements><camunda:formData>'
               '<camunda:formField id="upheld" label="Appeal upheld (pay the refund)" type="boolean" />'
               '<camunda:formField id="reviewNote" label="Reason for the decision" type="string" />'
               '</camunda:formData></bpmn:extensionElements>')


def handle_appeal() -> Grid:
    lanes = [("Lane_System", "Claims system", 0, 0), ("Lane_CaseWorker", "Case worker", 1, 1)]
    p = Grid(A.APPEAL_KEY, "Movia: handle appeal (once per appeal)", True, top=60, rows=(0, 1))
    p.lanes = lane_rows(p, lanes)
    sys_, cw = "Lane_System", "Lane_CaseWorker"
    p.put("Start_Appeal", "startEvent", A.APPEAL_RECEIVED, 0, body=message_start(A.APPEAL_MESSAGE), lane=sys_)
    p.put("Task_Retrieve", "serviceTask", A.RETRIEVE_CLAIM, 1, attrs=service(A.RETRIEVE_CLAIM), lane=sys_)
    p.put("Task_Review", "userTask", A.REVIEW_APPEAL, 2, 1, attrs=' camunda:candidateGroups="caseworker"',
          body=REVIEW_FORM, lane=cw)
    p.put("Gateway_Upheld", "exclusiveGateway", "Appeal upheld?", 3, 1, lane=cw)
    p.put("Task_Refund", "businessRuleTask", A.CALC_REFUND, 4, attrs=REFUND[0],
          body=REFUND[1], lane=sys_)
    p.put("Task_PayOut", "serviceTask", A.PAY_OUT, 5, attrs=service(A.PAY_OUT), lane=sys_)
    p.put("Gateway_UpheldJoin", "exclusiveGateway", "", 6, lane=sys_)
    p.put("Task_SendAppeal", "serviceTask", A.SEND_APPEAL_DECISION, 7, attrs=service(A.SEND_APPEAL_DECISION),
          lane=sys_)
    p.put("End_Appeal", "endEvent", A.APPEAL_DECIDED, 8, lane=sys_)
    p.flow("Start_Appeal", "Task_Retrieve")
    p.flow("Task_Retrieve", "Task_Review")
    p.flow("Task_Review", "Gateway_Upheld")
    p.flow("Gateway_Upheld", "Task_Refund", "yes", "${upheld}")
    up, join = p.nodes["Gateway_Upheld"], p.nodes["Gateway_UpheldJoin"]
    p.flow("Gateway_Upheld", "Gateway_UpheldJoin", "no", "${!upheld}", wp=[up.right, (join.x, up.y), join.bottom])
    p.flow("Task_Refund", "Task_PayOut")
    p.flow("Task_PayOut", "Gateway_UpheldJoin")
    p.flow("Gateway_UpheldJoin", "Task_SendAppeal")
    p.flow("Task_SendAppeal", "End_Appeal")
    return p.close(8)


# ---- Passenger journey (customer-oriented, not executable) ---------------------------------------------

def passenger_journey():
    p = Grid("passenger-journey", "Passenger", False, top=230, rows=(-1, 1))
    p.put("Start_Disrupted", "startEvent", "Trip disrupted", 0)
    p.put("Gateway_Notified", "exclusiveGateway", "Notified by Movia?", 1, label="right")
    p.put("Task_ReadNotice", "task", "Read eligibility notice", 2, -1)
    p.put("Gateway_NotifiedJoin", "exclusiveGateway", "", 3)
    p.put("Task_Taxi", "task", "Take a taxi", 4)
    p.put("Task_Submit", "task", "Submit claim with receipt", 5)
    p.put("Task_Decision", "task", "Receive decision", 6)
    p.put("Gateway_Accept", "exclusiveGateway", "Accept the decision?", 7)
    p.put("Task_Appeal", "task", "Submit appeal", 8, -1)
    p.put("Task_AppealDecision", "task", "Receive appeal decision", 9, -1)
    p.put("Gateway_AcceptJoin", "exclusiveGateway", "", 10)
    p.put("End_Settled", "endEvent", "Claim settled", 11)
    p.flow("Start_Disrupted", "Gateway_Notified")
    p.flow("Gateway_Notified", "Task_ReadNotice", "yes")
    p.detour("Gateway_Notified", "Gateway_NotifiedJoin", 1, "no")
    p.flow("Task_ReadNotice", "Gateway_NotifiedJoin")
    p.flow("Gateway_NotifiedJoin", "Task_Taxi")
    p.flow("Task_Taxi", "Task_Submit")
    p.flow("Task_Submit", "Task_Decision")
    p.flow("Task_Decision", "Gateway_Accept")
    p.flow("Gateway_Accept", "Task_Appeal", "no")
    p.flow("Task_Appeal", "Task_AppealDecision")
    p.flow("Task_AppealDecision", "Gateway_AcceptJoin")
    p.flow("Gateway_Accept", "Gateway_AcceptJoin", "yes")
    p.flow("Gateway_AcceptJoin", "End_Settled")
    p.close(11)
    movia = ("Participant_Movia", "Movia customer service", (100, 40, p.pool[2], 70))
    up = lambda n: (n.x, n.y - n.h / 2)  # noqa: E731
    pool_bottom = 110
    flows = [
        ("Msg_Notice", "eligibility notice", "Participant_Movia", "Task_ReadNotice", True),
        ("Msg_Claim", "claim", "Task_Submit", "Participant_Movia", False),
        ("Msg_Decision", "decision", "Participant_Movia", "Task_Decision", True),
        ("Msg_Appeal", "appeal", "Task_Appeal", "Participant_Movia", False),
        ("Msg_AppealDecision", "appeal decision", "Participant_Movia", "Task_AppealDecision", True),
    ]
    mflows = []
    for mid, name, s, t, inbound in flows:
        task = p.nodes[t if inbound else s]
        x, y = up(task)
        x += -20 if inbound else 20
        wp = [(x, pool_bottom), (x, y)] if inbound else [(x, y), (x, pool_bottom)]
        mflows.append((mid, name, s, t, wp))
    return p, movia, mflows


# ---- Collaboration overview (all collapsed) --------------------------------------------------------------

def collaboration_overview():
    w, gap, h = 330, 90, 80
    xs = [160 + i * (w + gap) for i in range(3)]
    full = xs[2] + w - 160
    pools = [
        ("Participant_Passenger", "Passenger (passenger journey)", (160, 60, full, h)),
        ("Participant_Assess", "Movia: assess disruption", (xs[0], 300, w, h)),
        ("Participant_Decide", "Movia: decide claim and pay out", (xs[1], 300, w, h)),
        ("Participant_Appeal", "Movia: handle appeal", (xs[2], 300, w, h)),
        ("Participant_Monitor", "Delay monitor (CEP) and recorder", (160, 540, full, h)),
    ]
    top, bot = 140, 300  # passenger pool bottom, Movia pools top
    mtop, mbot = 380, 540  # Movia pools bottom, monitor top
    v = lambda x, y1, y2: [(x, y1), (x, y2)]  # noqa: E731
    flows = [
        ("Msg_Delay", "delay situation", "Participant_Monitor", "Participant_Assess", v(xs[0] + 70, mbot, mtop)),
        ("Msg_Assessment", "disruption assessment", "Participant_Assess", "Participant_Monitor",
         v(xs[0] + 230, mtop, mbot)),
        ("Msg_Notice", "eligibility notice", "Participant_Assess", "Participant_Passenger", v(xs[0] + 165, bot, top)),
        ("Msg_Claim", "claim with receipt", "Participant_Passenger", "Participant_Decide", v(xs[1] + 80, top, bot)),
        ("Msg_Decision", "decision", "Participant_Decide", "Participant_Passenger", v(xs[1] + 250, bot, top)),
        ("Msg_Exclusion", "exclusion", "Participant_Assess", "Participant_Decide",
         [(xs[0] + w, 340), (xs[1], 340)]),
        ("Msg_Outcome", "claim outcome", "Participant_Decide", "Participant_Monitor", v(xs[1] + 165, mtop, mbot)),
        ("Msg_Appeal", "appeal", "Participant_Passenger", "Participant_Appeal", v(xs[2] + 80, top, bot)),
        ("Msg_AppealDecision", "appeal decision", "Participant_Appeal", "Participant_Passenger",
         v(xs[2] + 250, bot, top)),
    ]
    return pools, flows


# ---- writing ---------------------------------------------------------------------------------------

TYPED_TASKS = ("serviceTask", "businessRuleTask", "userTask", "sendTask", "receiveTask", "manualTask")


def processdoctor(xml: str) -> str:
    """The same model with every typed task written as a plain <bpmn:task>, which is all processdoctor reads."""
    return re.sub(r"<(/?)bpmn:(" + "|".join(TYPED_TASKS) + r")\b", r"<\1bpmn:task", xml)


def write(name: str, xml: str, doctor: bool = False) -> None:
    os.makedirs(OUT, exist_ok=True)
    files = [(name + ".bpmn", xml)] + ([(name + ".processdoctor.bpmn", processdoctor(xml))] if doctor else [])
    for fn, text in files:
        with open(os.path.join(OUT, fn), "w", encoding="utf-8") as fh:
            fh.write(text)
        print("wrote", os.path.relpath(os.path.join(OUT, fn)))


def main() -> None:
    for name, build, msgs in (
        ("assess-disruption", assess_disruption, [A.DELAY_MESSAGE]),
        ("decide-claim", decide_claim, [A.CLAIM_MESSAGE]),
        ("handle-appeal", handle_appeal, [A.APPEAL_MESSAGE]),
    ):
        write(name, document(f"Definitions_{name}", [build()], messages=[(f"Message_{m}", m) for m in msgs],
                             doc=AUTHOR), doctor=True)
    p, movia, mflows = passenger_journey()
    write("passenger-journey", document("Definitions_passenger_journey", [p], collapsed=[movia],
                                        message_flows=mflows, doc=AUTHOR))
    pools, flows = collaboration_overview()
    write("collaboration-overview", document("Definitions_collaboration_overview", [], collapsed=pools,
                                             message_flows=flows, doc=AUTHOR))


if __name__ == "__main__":
    main()
